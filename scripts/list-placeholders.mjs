/**
 * Lists every placeholder still waiting for Clifford's real content:
 * any text like [Clifford's …], [Placeholder …] or [TODO …] in the site's source.
 *
 *   npm run placeholders            print the list
 *   npm run placeholders -- --readme  also refresh the list at the end of README.md
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const RE = /\[(?:Clifford['’]s|Clifford |Placeholder|TODO)[^\[\]]*\]/g;
const ROOTS = ['src/content', 'src/pages', 'src/config', 'src/components'];
const EXT = /\.(md|mdx|json|astro|ts)$/;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : EXT.test(p) ? [p] : [];
  });
}

let total = 0;
const md = [];
for (const file of ROOTS.flatMap(walk).sort()) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const hits = [];
  lines.forEach((line, i) => {
    // Skip code comments that merely explain the convention.
    if (/^\s*(\*|\/\/)/.test(line)) return;
    for (const m of line.matchAll(RE)) hits.push(`  line ${i + 1}: ${m[0]}`);
  });
  if (hits.length) {
    total += hits.length;
    const unique = [...new Set(hits.map((h) => h.replace(/^\s*line \d+: /, '')))];
    md.push(`\n**\`${relative('.', file)}\`**\n`, ...unique.map((u) => `- [ ] ${u.replace(/\|/g, '\\|')}`));
    console.log(`\n${relative('.', file)}  (${hits.length})`);
    console.log(hits.join('\n'));
  }
}
console.log(`\n${total} placeholder(s) left to fill in.`);

if (process.argv.includes('--readme')) {
  const START = '<!-- PLACEHOLDER-LIST:START -->';
  const END = '<!-- PLACEHOLDER-LIST:END -->';
  const readme = readFileSync('README.md', 'utf8');
  const i = readme.indexOf(START);
  const j = readme.indexOf(END);
  if (i < 0 || j < 0) throw new Error('README.md is missing the placeholder-list markers');
  const body = `${START}\n\n_${total} placeholders in total (generated by \`npm run placeholders -- --readme\`)._\n${md.join('\n')}\n\n`;
  writeFileSync('README.md', readme.slice(0, i) + body + readme.slice(j));
  console.log('README.md updated.');
}
